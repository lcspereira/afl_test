from datetime import datetime

from sqlalchemy import delete
from sqlalchemy.ext.asyncio import AsyncSession
from datetime import datetime, timezone
from sqlalchemy.future import select

from app.domain.task import Task, TaskCreate, TaskUpdate
from app.infrastructure.database.models import TaskRecord


class SqlAlchemyTaskRepository:
    def __init__(self, session: AsyncSession) -> None:
        self._session = session

    async def add(self, task: TaskCreate) -> Task:
        task.data_criacao = datetime.now(timezone.utc)
        task_record = TaskRecord(
            id=None,  # ID will be generated by the database
            id_usuario=task.id_usuario,
            titulo=task.titulo,
            descricao=task.descricao,
            status=task.status,
            data_criacao=task.data_criacao,
        )
        self._session.add(task_record)
        await self._session.commit()
        await self._session.refresh(task_record)
        return self._to_entity(task_record)

    async def get_by_id(self, task_id: int) -> Task | None:
        task = await self._session.scalar(
            select(TaskRecord).where(TaskRecord.id == task_id)
        )
        return self._to_entity(task) if task else None

    async def list_all(self) -> list[Task]:
        result = await self._session.execute(select(TaskRecord))
        tasks = result.scalars().all()
        return [self._to_entity(task) for task in tasks]

    async def list_by_user_id(self, user_id: int) -> list[Task]:
        result = await self._session.execute(
            select(TaskRecord).where(TaskRecord.id_usuario == user_id)
        )
        tasks = result.scalars().all()
        return [self._to_entity(task) for task in tasks]

    async def remove(self, task_id: int) -> None:
        stmt = delete(TaskRecord).where(TaskRecord.id == task_id)
        await self._session.execute(stmt)
        await self._session.commit()

    async def update(self, task_id: int, task: TaskUpdate, id_usuario: int) -> Task:
        current_task = await self._session.scalar(
            select(TaskRecord).where(TaskRecord.id == task_id)
        )
        if not current_task:
            raise ValueError("Tarefa não encontrada")
        if current_task.id_usuario != id_usuario:
            raise PermissionError("Não autorizado a atualizar esta tarefa")

        current_task.titulo = task.titulo if task.titulo is not None else current_task.titulo
        current_task.descricao = task.descricao if task.descricao is not None else current_task.descricao
        current_task.status = task.status if task.status is not None else current_task.status

        updated_task = await self._session.merge(current_task)
        await self._session.commit()
        await self._session.refresh(updated_task)
        return self._to_entity(updated_task)

    @staticmethod
    def _to_entity(task: TaskRecord) -> Task:
        return Task(
            id=task.id,
            id_usuario=task.id_usuario,
            titulo=task.titulo,
            descricao=task.descricao,
            status=task.status,
            data_criacao=task.data_criacao,
        )
